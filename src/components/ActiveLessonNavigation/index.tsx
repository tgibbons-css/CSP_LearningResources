import React, {createContext, useContext, useId, useState, type ReactNode} from 'react';
import Link from '@docusaurus/Link';

export type LessonHeading = {id: string; value: string; level: number};
export type ActiveLesson = {href: string; headings: readonly LessonHeading[]};

const LessonContext = createContext<{
  lesson: ActiveLesson | null;
  setLesson: (lesson: ActiveLesson | null) => void;
}>({lesson: null, setLesson: () => {}});

export function ActiveLessonProvider({children}: {children: ReactNode}) {
  const [lesson, setLesson] = useState<ActiveLesson | null>(null);
  return <LessonContext.Provider value={{lesson, setLesson}}>{children}</LessonContext.Provider>;
}

export const useActiveLesson = () => useContext(LessonContext);

export default function ActiveLessonNavigation({href, headings, onNavigate}: ActiveLesson & {onNavigate?: () => void}) {
  const [expanded, setExpanded] = useState(true);
  const listId = useId();
  if (!headings.length) return null;
  return <div className="active-lesson-sections">
    <button type="button" className="active-lesson-sections-toggle" aria-expanded={expanded}
      aria-controls={listId} onClick={() => setExpanded(!expanded)}>
      <span aria-hidden="true">{expanded ? '▾' : '▸'}</span> On this page
    </button>
    <ul id={listId} className="menu__list active-lesson-section-list" hidden={!expanded}>
      {headings.map((heading) => <li key={heading.id} className={heading.level > 2 ? 'active-lesson-subsection' : undefined}>
        <Link className="menu__link active-lesson-section-link" to={`${href}#${heading.id}`}
          onClick={onNavigate}
          // Heading HTML is generated by Docusaurus from the authored lesson.
          dangerouslySetInnerHTML={{__html: heading.value}} />
      </li>)}
    </ul>
  </div>;
}
